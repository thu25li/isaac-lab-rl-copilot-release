class TestSyntaxCheck:
    def test_valid_syntax_passes(self, validator):
        result = validator.validate_code(VALID_CODE)
        assert "syntax" in result["checks"]
        # Syntax itself doesn't fail (other checks may)
        assert not any("Syntax error" in e for e in result["errors"])

    def test_invalid_syntax_caught(self, validator):
        bad_code = "def broken(:\n    pass"
        result = validator.validate_code(bad_code)
        assert result["valid"] is False
        assert any("Syntax error" in e for e in result["errors"])

    def test_syntax_error_short_circuits(self, validator):
        # If syntax fails, subsequent checks shouldn't run
        result = validator.validate_code("def broken(:")
        # Only syntax check should have run
        assert result["checks"] == ["syntax"]


