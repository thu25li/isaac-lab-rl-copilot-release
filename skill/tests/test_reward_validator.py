class TestEdgeCases:
    def test_none_code_raises_type_error(self, validator):
        with pytest.raises(TypeError, match="code"):
            validator.validate_code(None)

    def test_empty_string_code_returns_invalid(self, validator):
        """Empty string parses as empty module — should fail imports check."""
        result = validator.validate_code("")
        assert result["valid"] is False
        assert any("configclass" in e for e in result["errors"])

    def test_weight_zero_triggers_warning(self, validator):
        code = VALID_CODE.replace(
            "weight=1.0",
            "weight=0.0",
        )
        result = validator.validate_code(code)
        # weight=0 for a tracking term should trigger a warning
        assert any("0" in w or "zero" in w.lower() for w in result["warnings"])

    def test_weight_nan_does_not_crash(self, validator):
        """NaN weight should not crash the validator — skip or warn."""
        code = VALID_CODE.replace(
            "weight=1.0",
            "weight=float('nan')",
        )
        # Should not raise
        result = validator.validate_code(code)
        assert isinstance(result["valid"], bool)

    def test_validate_file_with_directory_raises(self, validator, tmp_path):
        """Passing a directory path should raise a clear error, not PermissionError."""
        with pytest.raises((IsADirectoryError, ValueError, OSError)):
            validator.validate_file(tmp_path)
